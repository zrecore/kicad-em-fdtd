#!/usr/bin/env python3
"""Writes data/colormaps.json from the CC0 colormap tables of the matplotlib colormaps (viridis, magma,
inferno, plasma), read as text from a copy of BIDS/colormap's colormaps.py (never executed).

    python3 scripts/make_colormaps.py PATH/TO/colormaps.py > data/colormaps.json

The source file's header (read 2026-11-20) says the colormaps are released under CC0 / public domain and asks
for credit: Nathaniel J. Smith, Stefan van der Walt and (viridis) Eric Firing. No other tool is needed."""
import json
import re
import sys

NOTES = {
    "viridis": "Sequential; designed by its authors to be perceptually uniform and readable with common "
    "colour-vision deficiencies (their statement; not independently verified here).",
    "magma": "Sequential, black to light yellow through purple and pink; perceptually uniform by design.",
    "inferno": "Sequential, black to light yellow through purple and orange; perceptually uniform by design.",
    "plasma": "Sequential, blue-purple to yellow; perceptually uniform by design.",
}


def main(path):
    text = open(path, encoding="utf-8").read()
    maps = {}
    for name in ("magma", "inferno", "plasma", "viridis"):
        m = re.search(r"_%s_data = \[(.*?)\]\s*\n\s*\n" % name, text, re.S)
        if not m:
            m = re.search(r"_%s_data = \[(.*?)\]\]" % name, text, re.S)
            body = m.group(1) + "]" if m else None
        else:
            body = m.group(1)
        rows = re.findall(r"\[\s*([0-9.]+)\s*,\s*([0-9.]+)\s*,\s*([0-9.]+)\s*\]", body)
        if len(rows) != 256:
            raise SystemExit("%s: expected 256 rows, found %d" % (name, len(rows)))
        hexes = ["#%02X%02X%02X" % tuple(int(round(float(v) * 255)) for v in r) for r in rows]
        maps[name] = {"kind": "sequential", "note": NOTES[name], "colours": hexes}
    out = {
        "_comment": "Sequential colour maps for the 3D volume's magnitude view (View setting 'Volume colour "
        "map'). 256 entries each, dark to light, hex RRGGBB. Generated by scripts/make_colormaps.py.",
        "source": "https://github.com/BIDS/colormap (colormaps.py), the matplotlib colormaps by Nathaniel J. "
        "Smith, Stefan van der Walt and (viridis) Eric Firing",
        "licence": "CC0 1.0 (public domain dedication), stated in the header of the source file; credit "
        "requested and given in CREDITS.md",
        "maps": maps,
    }
    json.dump(out, sys.stdout, indent=1)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main(sys.argv[1])
